/******************************************************************************
 * File        : kernel.c
 * Description : Implements the RTOS Kernel APIs.
 ******************************************************************************/

#include "kernel.h"
#include "scheduler.h"
#include "tick.h"
#include "ready_queue.h"

/******************************************************************************
 * Function : Kernel_Init
 ******************************************************************************/

void Kernel_Init(void)
{
    /*------------------------------------------------------------
     * Initialize the system tick counter.
     *-----------------------------------------------------------*/
    Tick_Init();

    /*------------------------------------------------------------
     * Initialize all Ready Queues.
     *-----------------------------------------------------------*/
    ReadyQueue_Init();

    /*------------------------------------------------------------
     * Initialize the scheduler.
     *-----------------------------------------------------------*/
    Scheduler_Init();
}

/******************************************************************************
 * Function : Kernel_Start
 ******************************************************************************/

void Kernel_Start(void)
{
    /*------------------------------------------------------------
     * Start the scheduler.
     *-----------------------------------------------------------*/
    Scheduler_Run();
}